// Target generators helper
function generateTargetsForLevel(info: RawLevelInfo) {
  const targets: LevelConfig['targets'] = [];
  const count = info.targetCount;

  // Base coordinates spread across right half of canvas (X: 620 to 1140, Y: 180 to 480)
  const xSlots = [630, 750, 880, 1010, 1130];
  const types: TargetType[] = ['bullseye', 'apple', 'bell', 'balloon', 'star', 'shield'];
  const attachments: TargetAttachment[] = ['wall', 'pillar', 'rope', 'balloon_string', 'hanging', 'post'];

  for (let i = 0; i < count; i++) {
    const x = xSlots[i % xSlots.length];
    const y = 220 + (i % 3) * 110;
    const type = types[(info.num + i) % types.length];
    const attach = attachments[(info.num + i) % attachments.length];

    let movement: TargetMovementType = i % 2 === 0 ? 'vertical' : 'horizontal';
    if (info.hasPendulum && i === 1) movement = 'pendulum';
    if (info.hasSine && i === (count - 1)) movement = 'sine';

    let radius = Math.max(12, info.radiusBase - (type === 'apple' ? 4 : 0));
    let points = 50 + info.num * 4 + (type === 'apple' ? 40 : type === 'star' ? 50 : 20);

    const speed = info.speedBase + (i * 0.2);
    const range = 110 + (i * 15);
    const phase = (i * Math.PI) / 2.5;

    targets.push({
      type,
      x,
      y,
      radius,
      points,
      attachedTo: movement === 'pendulum' ? 'hanging' : type === 'balloon' ? 'balloon_string' : attach,
      movement,
      speed,
      range,
      phase,
      pivotX: x,
      pivotY: 60,
      ropeLength: 200 + i * 15,
      maxSwingAngle: 0.45 + (info.num * 0.007),
    });
  }

  return targets;
}

// Export 40 fully realized levels
export const LEVELS: LevelConfig[] = RAW_LEVELS.map((info) => {
  return {
    levelNumber: info.num,
    nameBn: info.nameBn,
    nameEn: info.nameEn,
    subtitleBn: info.subBn,
    subtitleEn: info.subEn,
    backgroundTheme: info.theme,
    arrowsAllowed: info.arrows,
    wind: info.wind,
    targets: generateTargetsForLevel(info),
    obstacles: info.obstacles,
  };
});
